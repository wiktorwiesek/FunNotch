//
//  ClipboardManager.swift
//  FunNotch
//
//  Keeps a short history of what you have copied, so the notch can hand it
//  back. Entries marked concealed (password managers) or transient are skipped,
//  following the org.nspasteboard convention.
//

import AppKit
import Combine
import SwiftUI

struct ClipboardEntry: Identifiable, Equatable {
    enum Payload: Equatable {
        case text(String)
        case image(NSImage)
        case files([URL])
    }

    let id: UUID
    let payload: Payload
    let copiedAt: Date
    /// Name of the app that put it there, when we could tell.
    let sourceApp: String?
    /// Pinned entries stay put and survive the history limit.
    var isPinned: Bool = false

    var isText: Bool {
        if case .text = payload { return true }
        return false
    }

    /// One-line description for the tile. Capped, because tiles redraw on every
    /// hover and laying out several MB of copied log as a `Text` is slow.
    var preview: String {
        switch payload {
        case let .text(value):
            let head = value.drop(while: { $0.isWhitespace }).prefix(600)
            let trimmed = String(head).trimmingCharacters(in: .whitespacesAndNewlines)
            return trimmed.replacingOccurrences(of: "\r\n", with: " ")
                .replacingOccurrences(of: "\n", with: " ")
        case .image:
            return "Obraz"
        case let .files(urls):
            return urls.count == 1
                ? urls[0].lastPathComponent
                : Polish.count(urls.count, "plik", "pliki", "plików")
        }
    }

    /// What the clipboard search looks through: the text itself (to 200k
    /// characters, so a keystroke stays cheap), not the capped preview.
    var searchText: String {
        if case let .text(value) = payload { return String(value.prefix(200_000)) }
        return preview
    }

    var symbol: String {
        switch payload {
        case let .text(value):
            let smart = ClipboardSmart.kind(for: value)
            if smart != .plain { return smart.symbol }
            if value.hasPrefix("http://") || value.hasPrefix("https://") { return "link" }
            return "text.alignleft"
        case .image: return "photo"
        case .files: return "doc"
        }
    }

    static func == (lhs: ClipboardEntry, rhs: ClipboardEntry) -> Bool {
        lhs.id == rhs.id
    }
}

@MainActor
final class ClipboardManager: ObservableObject {
    static let shared = ClipboardManager()

    @Published private(set) var entries: [ClipboardEntry] = [] {
        didSet {
            // Recognised image text must not outlive its history entry.
            ClipboardOCRIndex.shared.prune(keeping: Set(entries.map(\.id)))
        }
    }

    private var timer: Timer?
    /// Sweeps expired entries while the app sits idle, so a history left alone
    /// overnight is already empty in the morning rather than emptying itself
    /// the next time you happen to copy something.
    private var expiryTimer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    /// Change count of writes we made ourselves, so pasting back does not
    /// re-record the same thing.
    private var ownChangeCount = -1
    private var cancellables = Set<AnyCancellable>()

    private let storageKey = "clipboardTextHistory"

    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private init() {
        restore()
        // Anything already past its expiry when the app starts goes now, before
        // the history is ever shown.
        if expireOldEntries() { persist() }
    }

    func start() {
        NotificationCenter.default.publisher(for: .settingsChanged)
            .compactMap { $0.object as? String }
            .filter { $0 == "clipboardHistoryEnabled" }
            .receive(on: RunLoop.main)
            .sink { [weak self] _ in self?.restartPolling() }
            .store(in: &cancellables)

        restartPolling()
        startExpirySweep()
    }

    private func startExpirySweep() {
        expiryTimer?.invalidate()
        // Hourly is plenty for a setting measured in hours, and the tolerance
        // lets macOS coalesce it with other timers instead of waking the CPU
        // on its own account.
        let timer = Timer(timeInterval: 3600, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                guard let self, self.expireOldEntries() else { return }
                self.persist()
            }
        }
        timer.tolerance = 300
        RunLoop.main.add(timer, forMode: .common)
        expiryTimer = timer
    }

    private func restartPolling() {
        timer?.invalidate()
        timer = nil
        guard Settings.shared.clipboardHistoryEnabled else { return }

        lastChangeCount = NSPasteboard.general.changeCount
        // macOS has no pasteboard-changed notification, so this polls the
        // change counter. The tolerance lets the wake-ups ride along with
        // other timers; nothing is copied behind a lock screen.
        let timer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in
            guard !SystemActivityMonitor.isScreenIdle else { return }
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.3
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        // Skip our own writes, and anything a password manager marked private.
        guard pasteboard.changeCount != ownChangeCount else { return }
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: [Self.concealedType, Self.transientType, Self.autoGeneratedType]) else {
            return
        }

        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL], !urls.isEmpty {
            record(.files(urls), source: source)
            return
        }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            record(.text(text), source: source)
            return
        }

        if let images = pasteboard.readObjects(forClasses: [NSImage.self], options: nil) as? [NSImage],
           let image = images.first {
            record(.image(image), source: source)
        }
    }

    private func record(_ payload: ClipboardEntry.Payload, source: String?) {
        // Copying the same thing twice should move it up, not duplicate it.
        if let index = entries.firstIndex(where: { $0.payload == payload }) {
            let existing = entries.remove(at: index)
            // The pin has to survive: copying a pinned snippet again used to
            // drop it from the pinned list and quietly make it expirable.
            entries.insert(
                ClipboardEntry(
                    id: existing.id, payload: payload, copiedAt: Date(),
                    sourceApp: source ?? existing.sourceApp, isPinned: existing.isPinned
                ),
                at: 0
            )
        } else {
            entries.insert(
                ClipboardEntry(id: UUID(), payload: payload, copiedAt: Date(), sourceApp: source),
                at: 0
            )
        }

        expireOldEntries()

        // Images are read for text in the background so search can find them.
        if let recorded = entries.first { ClipboardOCRIndex.shared.index(recorded) }

        // Pinned entries do not count against the limit and are never dropped.
        let limit = max(Settings.shared.clipboardHistoryLimit, 1)
        var unpinned = entries.filter { !$0.isPinned }
        if unpinned.count > limit {
            let doomed = Set(unpinned.suffix(unpinned.count - limit).map(\.id))
            entries.removeAll { doomed.contains($0.id) }
            unpinned = entries.filter { !$0.isPinned }
        }

        persist()
    }

    /// Puts an entry back on the pasteboard.
    func copyBack(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        switch entry.payload {
        case let .text(value):
            pasteboard.setString(value, forType: .string)
        case let .image(image):
            pasteboard.writeObjects([image])
        case let .files(urls):
            pasteboard.writeObjects(urls as [NSURL])
        }

        ownChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
    }

    /// Writes plain text produced by a smart action (a colour as HEX, a bare
    /// NIP) without the history recording it as something the user copied.
    func copyText(_ value: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(value, forType: .string)
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
    }

    /// Moves a copied file or image onto the shelf.
    @discardableResult
    func sendToShelf(_ entry: ClipboardEntry) -> Bool {
        switch entry.payload {
        case let .files(urls):
            return urls.reduce(false) { ShelfManager.shared.add(url: $1) || $0 }
        case let .image(image):
            guard let tiff = image.tiffRepresentation,
                  let bitmap = NSBitmapImageRep(data: tiff),
                  let png = bitmap.representation(using: .png, properties: [:])
            else { return false }
            return ShelfManager.shared.addTemporary(
                data: png,
                preferredName: "Obraz ze schowka \(ShelfManager.timestampSuffix()).png"
            )
        case let .text(value):
            guard let data = value.data(using: .utf8) else { return false }
            return ShelfManager.shared.addTemporary(
                data: data,
                preferredName: "Tekst ze schowka \(ShelfManager.timestampSuffix()).txt"
            )
        }
    }

    /// Fills the history with fixed entries, for snapshots.
    func injectPreviewEntries(_ payloads: [(ClipboardEntry.Payload, String?)]) {
        entries = payloads.enumerated().map { index, item in
            ClipboardEntry(
                id: UUID(),
                payload: item.0,
                copiedAt: Date(),
                sourceApp: item.1,
                isPinned: index == 0
            )
        }
    }

    func togglePin(_ entry: ClipboardEntry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[index].isPinned.toggle()
        // Pinned things belong at the front where they are easy to reach.
        let updated = entries.remove(at: index)
        if updated.isPinned {
            entries.insert(updated, at: 0)
        } else {
            let firstUnpinned = entries.firstIndex { !$0.isPinned } ?? entries.count
            entries.insert(updated, at: firstUnpinned)
        }
        persistPinned()
        persist()
    }

    /// Entries matching a search, pinned first.
    func filtered(by query: String) -> [ClipboardEntry] {
        let trimmed = query.trimmingCharacters(in: .whitespacesAndNewlines)
        // Case and diacritics are ignored so "zolty" finds "żółty", which
        // matters most for text read out of screenshots. "ł" is a letter of its
        // own, not an "l" with a mark, so `.diacriticInsensitive` leaves it
        // alone and it has to be folded by hand.
        func fold(_ text: String) -> String {
            text.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil)
                .replacingOccurrences(of: "ł", with: "l")
        }
        let needle = fold(trimmed)
        func contains(_ haystack: String) -> Bool {
            fold(haystack).contains(needle)
        }
        let matches = trimmed.isEmpty
            ? entries
            : entries.filter { entry in
                contains(entry.searchText) || (ClipboardOCRIndex.shared.text(for: entry.id).map(contains) ?? false)
            }
        return matches.sorted { lhs, rhs in
            if lhs.isPinned != rhs.isPinned { return lhs.isPinned }
            return lhs.copiedAt > rhs.copiedAt
        }
    }

    private func persistPinned() {
        let pinned = entries.filter(\.isPinned).compactMap { entry -> String? in
            guard case let .text(value) = entry.payload else { return nil }
            return value
        }
        Settings.shared.clipboardPinned = pinned
    }

    func remove(_ entry: ClipboardEntry) {
        entries.removeAll { $0.id == entry.id }
        persist()
    }

    /// Drops unpinned entries past their expiry. Pinned ones are exempt, the
    /// same as with the count limit: pinning is the way you say "keep this".
    ///
    /// Returns true when something was actually removed, so callers can avoid
    /// a pointless write to disk on the common no-op case.
    @discardableResult
    func expireOldEntries() -> Bool {
        let hours = Settings.shared.clipboardExpiryHours
        guard hours > 0 else { return false }
        let cutoff = Date().addingTimeInterval(-Double(hours) * 3600)
        let before = entries.count
        entries.removeAll { !$0.isPinned && $0.copiedAt < cutoff }
        return entries.count != before
    }

    /// Clears everything except pinned entries.
    func clear() {
        entries.removeAll { !$0.isPinned }
        persist()
    }

    // MARK: - Persistence
    //
    // Only text survives a relaunch: images would bloat the preferences, and
    // copied files may have moved by then.

    private func persist() {
        // Stored as [[text, copiedAt]] rather than a bare list of strings, so
        // an entry's age survives a relaunch. Without the timestamp everything
        // came back as `.distantPast`, which the expiry sweep would delete on
        // sight — the history would empty itself every launch.
        // UserDefaults is a property list that is rewritten whole on every
        // copy; a pasted log or CSV of several MB would stall each save, so
        // oversized text stays in memory for the session only.
        let rows: [[Any]] = entries.compactMap { entry in
            guard case let .text(value) = entry.payload, value.utf8.count <= 200_000 else { return nil }
            return [value, entry.copiedAt.timeIntervalSince1970]
        }
        UserDefaults.standard.set(Array(rows.prefix(50)), forKey: storageKey)
    }

    private func restore() {
        let pinned = Set(Settings.shared.clipboardPinned)
        let stored = UserDefaults.standard.array(forKey: storageKey) ?? []

        // Rows are [text, timestamp]; a plain string is the pre-1.0.2 format,
        // which is read once and rewritten in the new shape on the next save.
        // Those have no known age, so they are treated as copied just now
        // rather than expired immediately.
        let decoded: [(String, Date)] = stored.compactMap { row in
            if let text = row as? String { return (text, Date()) }
            guard let pair = row as? [Any],
                  let text = pair.first as? String else { return nil }
            let when = (pair.count > 1 ? pair[1] as? Double : nil).map(Date.init(timeIntervalSince1970:))
            return (text, when ?? Date())
        }
        guard !decoded.isEmpty else { return }

        entries = decoded.map {
            ClipboardEntry(
                id: UUID(),
                payload: .text($0.0),
                copiedAt: $0.1,
                sourceApp: nil,
                isPinned: pinned.contains($0.0)
            )
        }
    }
}
